/*
 * 問題のもとになるデータ(英語・国語)
 * ------------------------------------------------------------
 * 書式:「見出し|意味|覚え方のヒント(任意)」を1行ずつ並べています。
 * このデータから、問題・単語帳・単語テストを自動で作ります。
 * データを追加すると、そのまま問題数が増えます。
 */
window.WPS = window.WPS || {};
WPS.BANK = WPS.BANK || {};

function wpsParse(text) {
  return text.trim().split('\n').map(function (line) {
    var p = line.trim().split('|');
    return { t: p[0], m: p[1], h: p[2] || '' };
  }).filter(function (x) { return x.t && x.m; });
}
WPS.parseBank = wpsParse;

